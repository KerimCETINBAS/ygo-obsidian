import esbuild from "esbuild";
import { copyFileSync, mkdirSync, rmSync } from "node:fs";
import path from "node:path";
import process from "process";
import builtins from "builtin-modules";

const pluginId = "ygo-combo-builder";
const pluginFiles = ["main.js", "manifest.json", "styles.css"];

function publishPlugin() {
  const dist = path.resolve("dist");
  const vaultPlugin = path.resolve("example/.obsidian/plugins", pluginId);
  mkdirSync(dist, { recursive: true });
  mkdirSync(vaultPlugin, { recursive: true });
  copyFileSync("manifest.json", path.join(dist, "manifest.json"));
  copyFileSync("styles.css", path.join(dist, "styles.css"));
  for (const file of pluginFiles) copyFileSync(path.join(dist, file), path.join(vaultPlugin, file));
  rmSync("main.js", { force: true });
}

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
*/
`;

const prod = process.argv[2] === "production";
const test = process.argv[2] === "test";

if (test) {
  await esbuild.build({
    entryPoints: ["src/model.test.ts"],
    bundle: true,
    platform: "node",
    format: "cjs",
    outfile: "tmp/model.test.js",
    logLevel: "info",
  });
} else {
  const context = await esbuild.context({
    banner: { js: banner },
    entryPoints: ["src/main.ts"],
    bundle: true,
    external: ["obsidian", "electron", ...builtins],
    format: "cjs",
    target: "es2018",
    logLevel: "info",
    sourcemap: prod ? false : "inline",
    treeShaking: true,
    outfile: "dist/main.js",
    plugins: [
      {
        name: "publish-plugin",
        setup(build) {
          build.onEnd((result) => {
            if (result.errors.length) return;
            publishPlugin();
          });
        },
      },
    ],
  });

  await esbuild.build({
    entryPoints: ["preview/preview.ts"],
    bundle: true,
    format: "iife",
    target: "es2018",
    outfile: "preview/preview.js",
    logLevel: "info",
  });

  if (prod) {
    await context.rebuild();
    process.exit(0);
  } else {
    await context.watch();
  }
}
